"""Pydantic schemas for itinerary and activity management."""

from typing import Optional
import uuid
from pydantic import BaseModel, ConfigDict, Field


class Activity(BaseModel):
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = Field(..., min_length=1, description="Activity name or title")
    category: str = Field(
        default="sightseeing",
        description="Category: sightseeing, food, culture, nature, adventure, shopping, relaxation, nightlife",
    )
    description: str = Field(default="", description="Detailed description of the activity")
    location: str = Field(..., description="Location address or landmark name")
    latitude: float | None = Field(default=None, description="GPS latitude coordinate")
    longitude: float | None = Field(default=None, description="GPS longitude coordinate")
    start_time: str = Field(default="09:00", description="Activity start time (e.g. '09:00' or '14:30')")
    duration_minutes: int = Field(default=60, ge=1, description="Duration in minutes")
    estimated_cost: float = Field(default=0.0, ge=0.0, description="Estimated activity cost")
    currency: str = Field(default="USD", description="Currency symbol/code")
    travel_notes: str = Field(default="", description="Travel or transit tips for reaching this spot")
    order: int = Field(default=1, ge=0, description="Chronological sequence order within the day")

    model_config = ConfigDict(from_attributes=True)


class ActivityCreate(BaseModel):
    name: str = Field(..., min_length=1)
    category: str = Field(default="sightseeing")
    description: str = Field(default="")
    location: str = Field(...)
    latitude: float | None = None
    longitude: float | None = None
    start_time: str = Field(default="09:00")
    duration_minutes: int = Field(default=60, ge=1)
    estimated_cost: float = Field(default=0.0, ge=0.0)
    currency: str = Field(default="USD")
    travel_notes: str = Field(default="")
    order: Optional[int] = None


class ActivityUpdate(BaseModel):
    name: Optional[str] = None
    category: Optional[str] = None
    description: Optional[str] = None
    location: Optional[str] = None
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    start_time: Optional[str] = None
    duration_minutes: Optional[int] = Field(default=None, ge=1)
    estimated_cost: Optional[float] = Field(default=None, ge=0.0)
    currency: Optional[str] = None
    travel_notes: Optional[str] = None
    order: Optional[int] = None


class ItineraryDay(BaseModel):
    day_number: int = Field(..., ge=1, description="Day number of the trip (1, 2, ...)")
    date: str = Field(..., description="Calendar date of this day in YYYY-MM-DD")
    summary: str = Field(default="", description="Theme or overview of this day's plan")
    activities: list[Activity] = Field(default_factory=list, description="Ordered activities")
    daily_budget: float = Field(default=0.0, ge=0.0, description="Target or allocated budget for this day")
    notes: str = Field(default="", description="General recommendations and notes for this day")

    model_config = ConfigDict(from_attributes=True)


class Itinerary(BaseModel):
    trip_id: str = Field(..., description="Associated trip ID")
    days: list[ItineraryDay] = Field(default_factory=list, description="Days of the itinerary")
    total_estimated_cost: float = Field(default=0.0, ge=0.0, description="Total estimated cost across all days")
    currency: str = Field(default="USD", description="Currency symbol/code")
    planning_notes: str = Field(default="", description="Overall planning advice, packing tips, or notes")
    is_demo: bool = Field(default=False, description="True if generated by fallback demo provider")
    warnings: list[str] = Field(default_factory=list, description="Optimizer flags or budget/pacing warnings")
    created_at: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class ItineraryUpdate(BaseModel):
    days: Optional[list[ItineraryDay]] = None
    total_estimated_cost: Optional[float] = Field(default=None, ge=0.0)
    currency: Optional[str] = None
    planning_notes: Optional[str] = None


class RegenerateRequest(BaseModel):
    day_number: Optional[int] = Field(default=None, ge=1, description="Specific day to regenerate. If null, regenerates whole itinerary.")
    instructions: Optional[str] = Field(default="", description="Custom instructions or tweaks for regeneration")
